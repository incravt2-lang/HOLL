def key(r):
    return "v"+str(r["z"]) if r["mode"]=="vault" else f"{r['z']}_{r['choice']}"

def options(r):
    _,a,b=PLACES[key(r)]
    return {"loft":a,"pits":b} if key(r)=="6_0" else {"patha":a,"pathb":b}

RELICS={"measure":"Верная мера","cup":"Белая чаша","rivet":"Крепкая клёпка","reprieve":"Вторая запись"}
def active(h,effect):
    return h.get("route_relic")==effect and time.time()<h.get("route_until",0)

def pay(s,r):
    effect=r.pop("route_reward",None)
    if not effect:return ""
    news=[]
    for uid in r["party"]:
        h=s["heroes"][uid]
        if effect in RELICS:
            h.update(route_relic=effect,route_until=time.time()+1200)
            news.append(h["name"]+" · "+RELICS[effect]+" на 20 мин.")
        elif effect=="guide":
            h["safe_trail"]=True
            news.append(h["name"]+" · известен обход одной засады.")
    if effect in ("veya","hariton","guild"):
        eligible=[i for i in r["party"] if time.time()>=s["heroes"][i].get("writ_ready",0)]
        if eligible:
            ticket=r["id"]
            if len(eligible)==1:
                news.append(grant(s,eligible[0],ticket,effect))
            else:
                s.setdefault("writ_lots",{})[ticket]=dict(members=eligible,kind=effect,votes={},until=time.time()+86400)
                news.append("Грамота вынесена. Дневник → Грамоты: выберите «Нужна» или «Уступить».")
        else:news.append("Все участники уже получали грамоту за последние семь дней.")
    return "\n".join(news)

def grant(s,uid,ticket,kind):
    h=s["heroes"][uid];h.setdefault("writs",{})[ticket]=kind
    h["writ_ready"]=time.time()+7*86400
    return "Грамота досталась: "+h["name"]+"."

def lots(s,uid,ticket="",vote=""):
    now=time.time();lines=["Грамоты походов"];rows=[]
    for k,lot in list(s.get("writ_lots",{}).items()):
        if uid not in lot["members"]:continue
        votes=lot["votes"]
        if k==ticket and vote in ("need","pass") and now<lot["until"]:
            votes[uid]=vote
        if len(votes)==len(lot["members"]) or now>=lot["until"]:
            pool=[i for i in lot["members"] if votes.get(i)=="need" and s["heroes"][i].get("writ_ready",0)<=now]
            result=grant(s,random.choice(pool),k,lot["kind"]) if pool else "Желающих с правом на грамоту нет."
            for i in lot["members"]:s["heroes"][i]["writ_news"]=result
            del s["writ_lots"][k]
        else:
            lines.append(f"Грамота · {WRIT_NAMES[lot['kind']]} · ответили {len(votes)}/{len(lot['members'])}")
            rows.append([{"text":label,"callback_data":f"writ:{k}:{v}"} for label,v in (("Нужна","need"),("Уступить","pass"))])
    h=s["heroes"][uid]
    lines.extend("При себе · "+WRIT_NAMES[v] for v in h.get("writs",{}).values())
    if h.get("writ_news"):lines.append(h["writ_news"])
    return "\n".join(lines),rows

WRIT_NAMES={"veya":"Грамота Веи","hariton":"Грамота Харитона","guild":"Грамота Гильдии"}

def choose(s,r,path):
    from copy import deepcopy
    from cargo import needs
    from haul import preview,store
    from market import collect
    from notes import CATALOG
    from world import TIER_WEIGHTS
    e=path.effect
    r["fork_effect"]=e
    lines=[path.label, path.story]
    if e in (*RELICS,"guide",*WRIT_NAMES):
        r["route_reward"]=e
        lines.append("Находку нужно вынести из похода.")
    if e=="heal":
        healed=min(r["maxhp"]-r["hp"],r["maxhp"]//5)
        r["hp"]+=healed
        lines.append(f"Отряд восстановил {healed} ХП.")
    if e not in ("coins","rich","chest","toll","invoice","letter","accessory","gear"):
        return "\n".join(lines)
    z=r["z"]
    for uid in r["party"]:
        bag=r.setdefault("haul",{}).setdefault(uid,{})
        before=preview(s["heroes"][uid],bag)
        h=deepcopy(before)
        found=[]
        coins=(7+3*BANDS[z])*(2 if e in ("rich","chest") else 1)
        if e in ("toll","invoice","letter"):
            keys={"toll":["tollbook"],"invoice":["landing"],"letter":["address1","address2","address3"]}[e]
            unseen=[k for k in keys if k not in h.get("found_notes",[])]
            if unseen:
                k=random.choice(unseen)
                h.setdefault("found_notes",[]).append(k)
                found.append(CATALOG[k][1])
                if e=="letter":coins=0
        if e=="chest":
            found.append(collect(h,z,3+3*r["choice"],0.3,needs(s,uid)))
        if e in ("accessory","gear"):
            coins=0
            pool=loot_slots(z,11,h["class"])
            if e=="accessory":
                pool=[k for (zone,k),p in CLASS_PIECES.items() if zone==z and p[2]==h["class"] and gear_slot(z,k) in (0,3,7) and p[3]<2]
                tier=int(random.random()<0.2)
            else:tier=random.choices(range(5),weights=TIER_WEIGHTS["vault"])[0]
            k=random.choice([k for k in pool if RARITY[z,k]==tier] or pool)
            item=gear_names(z)[k]
            if item in h["items"]:coins=4*trade_value(z,k)
            else:h["items"][item]=[gear_stat(z,k),strength(z,k)]
            found.append(item)
        h["wallet"]+=coins
        if coins:found.append(f"{coins} мед.")
        store(bag,before,h)
        lines.append(h["name"]+" · "+", ".join(found))
    return "\n".join(lines)
